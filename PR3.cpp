#include <iostream>
#include <cmath>
#include <iomanip>

using namespace std;

int main() {
    // Налаштування виводу дробових чисел
    cout << fixed << setprecision(6);

    double x;
    cout << "Введіть значення x: ";
    cin >> x;

    // Перевірка допустимості значення x (x не може дорівнювати 0 через 1/x)
    if (x == 0) {
        cout << "Помилка: x не може дорівнювати 0 (ділення на нуль в 1/x)." << endl;
        return 1;
    }

    double y1 = 0; // Результат для скороченої форми if
    double y2 = 0; // Результат для повної форми if...else

    // Спосіб 1: Лише скорочена форма if()

    if (x <= 1) {
        y1 = (1.0 / x) + 4.0 - (8.0 + 0.65 * x);
    }
    if (x > 1 && x <= 5) {
        double arg = (6.1 + x) / 2.0;
        double ctg = 1.0 / tan(arg); // ctg(a) = 1 / tan(a)
        y1 = (1.0 / x) + 4.0 - (log(x) + ctg);
    }
    if (x > 5) {
        y1 = (1.0 / x) + 4.0 - sqrt(x + sqrt(2.0));
    }


    // Спосіб 2: Лише повна форма if()...else...

    if (x <= 1) {
        y2 = (1.0 / x) + 4.0 - (8.0 + 0.65 * x);
    }
    else {
        if (x <= 5) { // сюди потрапляємо, якщо x > 1
            double arg = (6.1 + x) / 2.0;
            double ctg = 1.0 / tan(arg);
            y2 = (1.0 / x) + 4.0 - (log(x) + ctg);
        }
        else { // сюди потрапляємо, якщо x > 5
            y2 = (1.0 / x) + 4.0 - sqrt(x + sqrt(2.0));
        }
    }

    // Вивід результатів
    cout << "\n--- Результати обчислень ---" << endl;
    cout << "Спосіб 1 (скорочена форма if): y = " << y1 << endl;
    cout << "Спосіб 2 (повна форма if-else): y = " << y2 << endl;

    return 0;
}